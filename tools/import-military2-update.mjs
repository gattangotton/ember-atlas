import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {decodeMessagePack} from './read-messagepack.mjs';
import {abilityName} from '../public/ability-names.js';
import {validateResearchSpecs} from '../public/strategy-model.js';
const dir=process.argv[2]||'.work/game-master-2026-10-09';
const bytes=fs.readFileSync(dir+'/Research');
const raw=decodeMessagePack(bytes).find(g=>g[0]===4);
const abilities=new Map(decodeMessagePack(fs.readFileSync(dir+'/Ability')).map(a=>[a[0],a]));
const load=name=>JSON.parse(fs.readFileSync('public/data/'+name+'.json'));
const mechanics=load('mechanics'),game=load('game-masters');
const {GAME_RESEARCH_ICONS:icons}=await import('../public/game-research-icons.js');
const expected=[305,306,307],added=[];
for(const masterId of expected){
 const n=raw[4].find(n=>n[0]===masterId);if(!n)throw Error('Missing military II node '+masterId);
 const id='research-3-'+(masterId-237),first=n[7][0],lab=first[0].find(r=>r[-1]===2)?.[0];
 const requirements=first[0].filter(r=>r[-1]===1).map(r=>{const parent=Object.entries(game.researchMapping).find(([,p])=>p.groupId===4&&p.masterId===r[1]);if(!parent)throw Error('Unknown prerequisite');return {id:parent[0],level:r[2]};});
 if(first[0].some(r=>![1,2].includes(r[-1]))||n[7].slice(1).some(l=>l[0]?.length))throw Error('Unsupported level prerequisites');
 const effects=n[7].map(l=>l[2].filter(e=>e[0]?.[0]!==1));
 if(effects.some(e=>e.length!==1||e[0][-1]!==1))throw Error('Unexpected research effect');
 const abilityId=effects[0][0][0][0],ability=abilities.get(abilityId);
 if(effects.some(e=>e[0][0][0]!==abilityId)||ability[1]!==1)throw Error('Unexpected effect units');
 const values=effects.map(e=>e[0][0][1]/100),levels=n[7].map(l=>[...[1,2,4,8].map(k=>l[4].find(r=>r[0]===k)?.[1]??0),l[5]??0]);
 const node={id,group:'軍事②',name:n[1],lab,source:{sheet:'PC版 Research 4',row:masterId},levels,parents:requirements.map(r=>r.id),linksConfirmed:true,documentedMax:n[7].length,addedAt:'2026-10-09'};
 const existing=mechanics.research.findIndex(r=>r.id===id);if(existing<0)mechanics.research.push(node);else mechanics.research[existing]=node;
 game.researchMapping[id]={groupId:4,masterId,name:n[1],lab,kind:'ability',abilityId};
 game.researchSpecs[id]={ability:abilityName(ability[3]),unit:'%',values,requirementsKnown:true,requirements,note:`PC版ゲーム設定（2026-10-09取得） / Research 4:${masterId} / Ability ${abilityId}。各Lvの合計値。研究所Lv.${lab}、前提研究Lv.${requirements[0].level}。`};
 game.researchCosts[id]=levels;
 const path='assets/game/research/'+String(n[3]).padStart(5,'0')+'.png';if(!fs.existsSync('public/'+path))throw Error('Missing icon '+path);
 icons[id]={path,masterId,iconId:n[3],name:n[1]};
 added.push({id,masterId,name:n[1],lab,requirements,values,levels,icon:path,position:n[5]});
}
validateResearchSpecs(game.researchSpecs,mechanics.research);
const mapped=new Set(Object.values(game.researchMapping).filter(m=>m.groupId===4).map(m=>m.masterId));
if(raw[4].some(n=>!mapped.has(n[0])))throw Error('Additional unmapped military research');
game.summary.research=Object.keys(game.researchMapping).length;game.summary.numericResearch=Object.keys(game.researchSpecs).length;
game.military2Update={capturedAt:'2026-10-09',sha256:createHash('sha256').update(bytes).digest('hex'),ids:added.map(a=>a.id)};
for(const [name,data] of [['mechanics',mechanics],['game-masters',game]])fs.writeFileSync('public/data/'+name+'.json',JSON.stringify(data,null,2)+'\n');
fs.writeFileSync('public/game-research-icons.js','// Research field[3] maps to Research/Thumbnail.\nexport const GAME_RESEARCH_ICONS='+JSON.stringify(icons)+';\n');
fs.writeFileSync('artifacts/military2-update-2026-10-09.json',JSON.stringify({...game.military2Update,added},null,2)+'\n');
console.log(added.map(a=>({name:a.name,lab:a.lab,values:a.values,requirements:a.requirements})));
